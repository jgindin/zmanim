	private void runTest(
		HebrewDate      startDate,
	  HebrewDate      endDate,
	  ZmanimLocation  location,
	  String          expected
	) {


		ZmanFormatter formatter = new ZmanFormatter( false );
		ZmanFormatter formatterWithSeconds = new ZmanFormatter( true );

		StringBuilder output = new StringBuilder();
		output.append( "Date           |  10.2 deg   |   11 deg    |  11.5 deg   |\n" );
		output.append( "---------------|-------------|-------------|-------------|\n" );

		while ( endDate.compareTo( startDate ) >= 0 ) {

			Zmanim zmanim = startDate.getZmanim( location, Zmanim.Type.Talit );
			List<Zman> zmans = zmanim.asList();

			output.append( String.format( "%d / %2d / %2d | ", startDate.getGregorianYear(), startDate.getGregorianMonth() + 1,
				startDate.getGregorianDayOfMonth() ) );
			for ( Zman zman : zmans ) {

				String time = formatter.formatZmanTime( zman );
				output.append( time ).append( "     | " );
			}
			output.append( "\n" );

			output.append( "               | " );
			for ( Zman zman : zmans ) {

				String time = formatterWithSeconds.formatZmanTime( zman );
				output.append( time ).append( "  | " );
			}
			output.append( "\n" );

			startDate = startDate.tomorrow();
		}

		Assert.assertEquals( expected, output.toString() );
	}


